}

local function assignProperties(data, properties, tableName)
	for name, location in pairs(properties) do
		local definition = data[name]
		if not definition then
			rom.log.warning("Missing Discord presence definition: " .. tableName .. "." .. name)
		else
			definition.DiscordRichPresence = location
		end
	end
end

function mod.AssignPresenceProperties()
	assignProperties(game.RoomData, roomPresenceAliases, "RoomData")
	assignProperties(game.EncounterData, encounterPresenceAliases, "EncounterData")
end
